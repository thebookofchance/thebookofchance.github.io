"""Author-approved public digital release overlay, 23 November 2026.

Runs after the legacy site generators to keep the released status canonical.
Never removes required caveats on proposed Fellowship services or certifies accessibility.
"""
from __future__ import annotations
import json, re
from pathlib import Path
from bs4 import BeautifulSoup
from xml.etree import ElementTree as ET

DATE='23 November 2026'
INDEXABLE=[
    'booklets/the-little-book-of-possibilities/',
    'publications/conversations-of-chance/',
    'publications/beginners-guide-to-confluent-humanism/',
    'publications/parables-of-chance/',
    'questions/',
    'journey/',
]

# Curated substitutions for wording generated by previous editorial-staging scripts.
CHANGES = [
    ('Editorial candidate · Free','Published · Free'),
    ('Revised editorial candidate','Released digital edition'),
    ('Editorial candidate 1.0-RC1','Digital edition 1.0 · Released 23 November 2026'),
    ('First editorial candidate 1.0-RC1','Author-approved digital edition 1.0'),
    ('Editorial candidate 1.0-RC2','Released digital edition 1.0-RC2'),
    ('Editorial candidate 1.0-RC3','Released digital edition 1.0-RC3'),
    ('Editorial candidate v0.1 — now presented within the publication cover system','Released digital edition v0.1 · 23 November 2026'),
    ('Final copyedit candidate v0.2.1','Released digital edition v0.2.1'),
    ('Editorial candidate v0.2, awaiting manuscript approval','Released digital edition v0.2'),
    ('Editorial candidate v0.2','Released digital edition v0.2'),
    ('Editorial candidate','Published'),
    ('editorial candidates','released publications'),
    ('editorial candidate','released publication'),
    ('PDF reader proof','PDF edition'),
    ('PDF proof','PDF edition'),
    ('reader proof','digital edition'),
    ('reader proofs','digital editions'),
    ('independent review and final release checks are still outstanding','independent accessibility certification is not claimed'),
    ('final review and accessibility checks outstanding','accessibility certification is not claimed'),
    ('pending final digital accessibility and production checks','not independently certified for accessibility'),
    ('prepared as released publications','available as published digital editions'),
    ('final editorial approval remains outstanding','author approval was recorded on 23 November 2026'),
    ('Final editorial approval remains outstanding','Author approval was recorded on 23 November 2026'),
    ('the cover is a concept pending final approval','the cover has been approved by H'),
    ('The cover is a concept pending final approval','The cover has been approved by H'),
]


def _clean_generated(s: str) -> str:
    for a,b in CHANGES:
        s=s.replace(a,b)
    return s


def apply_release_v031(root: Path) -> None:
    root=Path(root)
    # These blocks carry contextual status information that needs more than a find/replace.
    site_notes={
        'index.html': {
            '.v20-collection-foot': 'All nine titles in the Library are author-approved digital publications. Every title is free to read and requires no account.'
        },
        'downloads/index.html': {
            '.v20-catalogue-note': 'All nine Library publications are approved by H for public reading. The separate Questions About Chance FAQ is also available for free, with no account required.',
        },
        'letters/index.html': {
            '.letters-series-foot p': 'The first three Letters are published digital editions. Further Letters may follow occasionally; no fixed schedule is promised.'
        },
        'questions/index.html': {
            '.v23-editorial-note': 'This FAQ is approved by H for public reading. It does not mean that the proposed Council, membership or support programmes are operating. The digital edition is not independently certified for accessibility.'
        },
        'journey/index.html': {
            'section.v24-journey-close p': 'These routes are invitations to read and question, not personal diagnoses or promises of good fortune. You are welcome to disagree with any text.'
        },
        'reader/index.html': {
            '.v25-reader-footer p': 'Page numbers depend on your screen and text size. All digital editions and downloads remain available without an account.'
        },
    }
    indexable=set(INDEXABLE)
    for page in sorted(root.rglob('index.html')):
        rel=page.relative_to(root).as_posix()
        if any(x in page.parts for x in ('_build_beginner_guide','_build_parables','_build_faq')):
            continue
        t=page.read_text('utf8')
        # Keep unchanged HTML byte-for-byte: only release pages and site-wide
        # catalogue cards need reserialization, not the foundational chapters.
        if (rel not in site_notes and rel.removesuffix('index.html') not in indexable
                and not any(term in t for term in ('Editorial candidate','editorial candidate',
                    'Editorial proof','editorial proof','PDF reader proof','PDF proof'))):
            continue
        # Old book titles and candidate strings sometimes appear as HTML text, not attributes.
        t=_clean_generated(t)
        soup=BeautifulSoup(t,'html.parser')
        for selector,new_text in site_notes.get(rel,{}).items():
            el=soup.select_one(selector)
            if el:
                el.clear()
                el.append(new_text)
        # FAQ short-form catalogue badge is a released reader resource.
        if rel=='downloads/index.html':
            teaser=soup.select_one('.v23-faq-teaser .eyebrow')
            if teaser:teaser.string='Public reader resource · Published'
            for el in soup.select('.v20-status'):
                if 'Published' in el.get_text():el.string='Published · Free'
            # Distinguish actual formats from draft proofs without renaming legacy URLs.
            for text in soup.find_all(string=True):
                if 'The PDFs currently supplied are digital editions' in text:
                    text.replace_with('The PDF downloads preserve fixed page layouts; these editions are not independently certified for accessibility.')
        if rel=='index.html':
            for el in soup.select('.v20-status'):
                el.string='Published · Free'
        if rel in ['questions/index.html','journey/index.html','reader/index.html']:
            # Preserve eReader noindex for intentional duplicate-content reading interface.
            pass
        rel_route=rel.removesuffix('index.html')
        if rel_route in indexable:
            for meta in soup.find_all('meta', attrs={'name':'robots'}):
                if 'noindex' in meta.get('content','').lower():meta.decompose()
        if rel=='booklets/the-little-book-of-possibilities/index.html':
            # The editorial author note is obsolete, while the AI-assistance disclosure stays.
            for p in soup.find_all('p'):
                if 'Authorship and production:' in p.get_text(' ',strip=True):
                    text=p.get_text(' ',strip=True)
                    if 'Final editorial approval remains outstanding' in text or 'author approval was recorded' in text:
                        for node in p.find_all(string=True):
                            if 'Final editorial approval remains outstanding' in str(node):
                                node.replace_with(str(node).replace('Final editorial approval remains outstanding','H approved this edition for release on 23 November 2026'))
        if rel=='publications/parables-of-chance/index.html':
            for p in soup.find_all('p'):
                tx=p.get_text(' ',strip=True)
                if 'Editorial record' in tx and 'simulated-review' in tx:
                    for node in p.find_all(string=True):
                        if 'This remains a simulated-review candidate, not a final released edition.' in str(node):
                            node.replace_with(str(node).replace('This remains a simulated-review candidate, not a final released edition.','The revised edition was approved for public release on 23 November 2026.'))
                        if 'The cover remains the existing v0.1 proposal, unchanged.' in str(node):
                            node.replace_with(str(node).replace('The cover remains the existing v0.1 proposal, unchanged.','The current cover was subsequently approved as part of the release.'))
        page.write_text(str(soup),'utf8')

    # The post-processor runs on each fresh site build. Canonical JSON records must agree.
    catalogue_path=root/'source/publications.json'
    catalog=json.loads(catalogue_path.read_text('utf8'))
    for item in catalog.get('available',[]):
        item['status']='author-approved digital release · 23 November 2026'
    for item in catalog.get('letters',{}).get('issues',[]):
        item['status']='author-approved digital release · 23 November 2026'
    for kind in ('booklets','conversations','parables','guides','reader_resources'):
        for item in catalog.get(kind,[]):
            item['status']='author-approved digital release · 23 November 2026'
    if isinstance(catalog.get('guided_reading_journey'),dict):
        catalog['guided_reading_journey']['status']='Released reading resource; no account or tracking'
    catalogue_path.write_text(json.dumps(catalog,indent=2,ensure_ascii=False)+'\n','utf8')
    letter_path=root/'source/letters/catalogue.json'
    letters=json.loads(letter_path.read_text('utf8'))
    for item in letters.get('available',[]):item['status']='author-approved digital release · 23 November 2026'
    letter_path.write_text(json.dumps(letters,indent=2,ensure_ascii=False)+'\n','utf8')
    faq=root/'source/resources/questions-about-chance.json'
    data=json.loads(faq.read_text('utf8'))
    data['status']='author-approved digital release · 23 November 2026'
    faq.write_text(json.dumps(data,indent=2,ensure_ascii=False)+'\n','utf8')
    # Allow search engines to index each canonical approved work and the reading journey.
    sm=root/'sitemap.xml'
    ET.register_namespace('','http://www.sitemaps.org/schemas/sitemap/0.9')
    tree=ET.parse(sm); node=tree.getroot(); ns='{http://www.sitemaps.org/schemas/sitemap/0.9}'
    urls={el.text for el in node.findall('.//'+ns+'loc')}
    for route in INDEXABLE:
        target='https://thebookofchance.github.io/'+route
        if target not in urls:
            child=ET.SubElement(node,ns+'url')
            ET.SubElement(child,ns+'loc').text=target
    tree.write(sm,encoding='utf-8',xml_declaration=True)
    # Correct generated status manifest, preserving historical QA documents unchanged.
    mi=root/'SITE_CONTENT_MANIFEST.json'
    if mi.exists():
        manifest=json.loads(mi.read_text('utf8'))
        manifest['website_version']='0.31'
        manifest['literature_release']='Author-approved digital release, 23 November 2026'
        manifest['literature_titles_approved']=9
        manifest['faq_approved']=True
        manifest['forms_acceptance']='User reports deployed forms functioning; not independently retested by this release script'
        manifest['accessibility']='Tagged PDF exports; full assistive-technology testing and formal PDF/UA conformance not independently verified'
        for key in list(manifest):
            if key in ('letters_series_status','companion_status','conversations_status','possibilities_status','faq_status','editorial_release_gate','sitemap_publication_gate','resources_stage'):
                manifest[key]='Author-approved public release · 23 November 2026'
        if isinstance(manifest.get('guided_reading_journey'),dict):
            manifest['guided_reading_journey']['status']='Released reading resource'
        mi.write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+'\n','utf8')

if __name__=='__main__':
    apply_release_v031(Path(__file__).resolve().parents[1])
